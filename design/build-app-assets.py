"""Exports the approved pixel UI to the Next.js app from the same source as the style guide.

Run from the project root:  python -P design/build-app-assets.py
Writes:
  src/app/pixel.css   — colour tokens, 9-slice frame images and textures as CSS custom properties
  src/lib/sprites.ts  — sprite data (hero, coin, icons) for the <Sprite> component
Both files are GENERATED — edit design/build-style-guide.py or design/sprites/*.txt instead.
"""
import importlib.util
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent
APP = ROOT.parent
spec = importlib.util.spec_from_file_location("sg", ROOT / "build-style-guide.py")
sg = importlib.util.module_from_spec(spec)
spec.loader.exec_module(sg)
C = dict(sg.C)
C["butter-dark"] = "#8a6417"   # warning *text* on white (butter itself is too light to read)

# small 9x10 flame for the streak (original)
FLAME = [
    "....o....",
    "...oro...",
    "...orro..",
    "..orrro..",
    ".orryro..",
    ".oryyyro.",
    "oryywyyro",
    "oryywwyro",
    ".oryyyro.",
    "..ooooo..",
]
FLAME_PAL = {"o": C["ink"], "r": C["rose"], "y": C["butter"], "w": C["white"]}
LOCK = [
    "..ooo..",
    ".o...o.",
    ".o...o.",
    "ooooooo",
    "oyyyyyo",
    "oyyoyyo",
    "oyyoyyo",
    "ooooooo",
]


def frames():
    n = sg.nine
    f = {
        "panel": n(C["white"]), "panel-mint": n(C["mint"]), "panel-vl": n(C["violet-light"]),
        "dialog": sg.nine_double(C["white"]), "dialog-mint": sg.nine_double(C["mint"]),
        "banner": n(C["violet"]),
        "btn": n(C["violet"], edge=C["violet-dark"]), "btn-on": n(C["violet"], edge=C["violet-dark"], edge_top=True),
        "btn-sec": n(C["white"], edge=C["line"]), "btn-sec-on": n(C["white"], edge=C["line"], edge_top=True),
        "btn-buy": n(C["peach"], edge=C["peach-dark"]), "btn-buy-on": n(C["peach"], edge=C["peach-dark"], edge_top=True),
        "btn-danger": n(C["rose"], edge=C["ink"]), "btn-danger-on": n(C["rose"], edge=C["ink"], edge_top=True),
        "btn-off": n(C["line"], outline=C["gray"], edge=C["line"]),
        "input": n(C["white"], edge=C["mint"], edge_top=True),
        "input-focus": n(C["white"], outline=C["violet"], edge=C["mint"], edge_top=True),
        "slot": n(C["mint"], edge=C["mint-dark"], edge_top=True), "slot-locked": n(C["white"], outline=C["gray"]),
        "badge": n(C["white"], n=6, cut=1), "badge-rose": n(C["rose"], n=6, cut=1),
        "badge-violet": n(C["violet"], n=6, cut=1), "badge-butter": n(C["butter"], n=6, cut=1),
        "badge-mint": n(C["mint"], n=6, cut=1), "badge-vl": n(C["violet-light"], n=6, cut=1),
        "track": n(C["mint"], n=6, cut=1),
        "frame": n(C["white"]),
    }
    for r, fill, _ in sg.RANKS:
        f[f"rank-{r}"] = n(fill)
    return f


def css():
    out = ["/* GENERATED by design/build-app-assets.py — do not edit by hand. */", ":root {"]
    out += [f"  --{k}: {v};" for k, v in C.items()]
    out += [f'  --frame-{k}: url("{v}");' for k, v in frames().items()]
    store, stw = sg.stripes(C["white"], C["peach"])
    guild, _ = sg.stripes(C["white"], C["violet-light"])
    out += [
        f'  --tex-dots: url("{sg.DOTS}");',
        f'  --tex-store: url("{store}");',
        f'  --tex-guild: url("{guild}");',
        f"  --tex-stripe-size: {stw}px;",
        f'  --icon-arrow: url("{sg.uri(sg.runs_svg(sg.ARROW, {"#": C["ink"]}, 5, 3))}");',
        "}",
    ]
    return "\n".join(out) + "\n"


def ts():
    def sprite(name, rows, w, h):
        return f"export const {name}: SpriteData = {{ w: {w}, h: {h}, rows: {json.dumps(rows, indent=2)} }};\n"
    parts = [
        "// GENERATED by design/build-app-assets.py — do not edit by hand.\n",
        "export type SpriteData = { w: number; h: number; rows: string[] };\n",
        "export type Palette = Record<string, string>;\n\n",
        f"export const COLORS = {json.dumps(C, indent=2)} as const;\n\n",
        sprite("HERO", sg.HERO, sg.HERO_W, sg.HERO_H),
        sprite("HERO_SHADOW", sg.SHADOW, sg.HERO_W, 3),
        f"export const HERO_OUTFIT: Palette = {json.dumps(sg.OUTFIT, indent=2)};\n",
        f"export const HERO_SKINS: [string, string][] = {json.dumps([list(s) for s in sg.SKINS])};\n",
        f"export const HERO_HAIRS: string[] = {json.dumps([h[0] for h in sg.HAIRS])};\n",
        f"export const HERO_HAIR_NAMES: string[] = {json.dumps(sg.HAIR_NAMES)};\n\n",
        sprite("COIN", sg.COIN, 12, 12),
        f"export const COIN_PALETTE: Palette = {json.dumps(sg.COIN_PAL)};\n\n",
        sprite("ICON_CHECK", sg.CHECK, 7, 6),
        sprite("ICON_CURSOR", sg.CURSOR, 4, 7),
        sprite("ICON_FLAME", FLAME, 9, 10),
        f"export const FLAME_PALETTE: Palette = {json.dumps(FLAME_PAL)};\n\n",
        sprite("ICON_LOCK", LOCK, 7, 8),
        f"export const LOCK_PALETTE: Palette = {json.dumps({'o': C['ink'], 'y': C['butter']})};\n\n",
        f"export const RANK_STYLE: Record<string, {{ fill: string; text: string }}> = "
        f"{json.dumps({r: {'fill': f, 'text': t} for r, f, t in sg.RANKS}, indent=2)};\n",
    ]
    return "".join(parts)


if __name__ == "__main__":
    (APP / "src" / "app" / "pixel.css").write_text(css(), encoding="utf-8")
    (APP / "src" / "lib" / "sprites.ts").write_text(ts(), encoding="utf-8")
    print("wrote src/app/pixel.css and src/lib/sprites.ts")
